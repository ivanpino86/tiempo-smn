// Generates proxy/src/stations.js from the three SMN open data files.
// Usage (repo root): node proxy/scripts/build-stations.mjs
//
// The files share no id, so every station of estaciones_smn.txt is matched to its
// name in tiepre (observations) and pron5d (forecast) by normalized name:
//   1. explicit OVERRIDES, 2. exact normalized match, 3. match ignoring AERO/OBS/OBSERVATORIO
//      (only among names still unused, and only when unambiguous).
import { writeFile } from "node:fs/promises";
import {
  decodeText, normName, stripName, argentinaYmd, parseStations, parseObservations, parseForecast,
} from "../src/opendata.js";

const BASE = "https://ssl.smn.gob.ar/dpd/descarga_opendata.php?file=";

// Keyed by normName(station name from estaciones_smn.txt, which is truncated to 30 chars).
// Values are the raw names used in tiepre (obs) and pron5d (fc); omit a key to leave it unmatched.
const OVERRIDES = {
  "PRESIDENCIA ROQUE SAENZ PENA A": { obs: "Pcia. Roque Saenz Peña", fc: "PCIA._ROQUE_SAENZ_PEÑA_AERO" },
  "ESCUELA DE AVIACION MILITAR AE": { obs: "Esc. Aviación Militar", fc: "ESC.AVIACION_MILITAR_AERO" },
  "MERCEDES AERO CTES": { obs: "Mercedes", fc: "MERCEDES_AERO_(CTES)" },
  "AEROPARQUE AERO": { obs: "Aeroparque Buenos Aires" },
  "VILLA DE MARIA DEL RIO SECO": { obs: "Villa María Del Río Seco", fc: "VILLA_MARIA_DEL_RIO_SECO" },
  "JUJUY U N": { obs: "Jujuy Universidad Nacional" },
  "SANTA ROSA DE CONLARA AERO": { obs: "Santa Rosa del Conlara" },
  "SAUCE VIEJO AERO": { obs: "Santa Fe" }, // Santa Fe city airport is Sauce Viejo
  "BASE CARLINI EX JUBANY": { obs: "Base Carlini" },
};

async function get(file) {
  const res = await fetch(BASE + file);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return decodeText(new Uint8Array(await res.arrayBuffer()));
}

async function latestDaily(prefix, dir, parse, isEmpty) {
  for (let back = 0; back < 3; back++) {
    const file = `${dir}/${prefix}${argentinaYmd(new Date(), back)}.txt`;
    try {
      const parsed = parse(await get(file));
      if (!isEmpty(parsed)) return parsed;
    } catch { /* try the previous day */ }
  }
  throw new Error(`no recent ${prefix} file`);
}

const stations = parseStations(await get("observaciones/estaciones_smn.txt"));
const obsRows = await latestDaily("tiepre", "observaciones", parseObservations, (r) => !r.length);
const fcNames = Object.keys(await latestDaily("pron", "pron5d", parseForecast, (r) => !Object.keys(r).length));
const obsNames = obsRows.map((r) => r.name);

function matcher(names) {
  const used = new Set();
  const byNorm = new Map(names.map((n) => [normName(n), n]));
  return {
    names, used,
    exact(norm) { const n = byNorm.get(norm); return n && !used.has(n) ? n : null; },
    loose(station) {
      const key = stripName(station);
      const free = names.filter((n) => !used.has(n) && stripName(n) === key);
      return free.length === 1 ? free[0] : null;
    },
  };
}
const obs = matcher(obsNames);
const fc = matcher(fcNames);
const pick = (m, kind, st, over) => {
  const n = (over && over[kind]) || m.exact(normName(st.name));
  if (n) m.used.add(n);
  return n || null;
};

const table = stations.map((st) => ({ st, over: OVERRIDES[normName(st.name)] }));
// Pass 1: overrides + exact; pass 2: loose, so exact matches are never stolen by a loose one
const result = table.map(({ st, over }) => ({ ...st, obs: pick(obs, "obs", st, over), fc: pick(fc, "fc", st, over) }));
for (const r of result) {
  if (!r.obs) { r.obs = obs.loose(r.name); if (r.obs) obs.used.add(r.obs); }
  if (!r.fc) { r.fc = fc.loose(r.name); if (r.fc) fc.used.add(r.fc); }
}

const warn = (msg) => process.stderr.write(msg + "\n");
for (const r of result) if (!r.obs || !r.fc) warn(`station without ${[!r.obs && "obs", !r.fc && "fc"].filter(Boolean).join("+")}: ${r.name} (${r.wmo})`);
for (const n of obsNames) if (!obs.used.has(n)) warn(`unused tiepre name: ${n}`);
for (const n of fcNames) if (!fc.used.has(n)) warn(`unused pron5d name: ${n}`);

const body = result.map((r) => "  " + JSON.stringify(r)).join(",\n");
const out = `// GENERATED by proxy/scripts/build-stations.mjs - do not edit by hand.
// ${result.length} stations; obs = name in tiepre*.txt, fc = name in pron*.txt (null when absent).
export const STATIONS = [
${body},
];
`;
await writeFile(new URL("../src/stations.js", import.meta.url), out);
const c = (k) => result.filter((r) => r[k]).length;
warn(`wrote ${result.length} stations (obs ${c("obs")}/${obsNames.length}, fc ${c("fc")}/${fcNames.length})`);
